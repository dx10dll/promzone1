#!/usr/bin/env python3
"""1.27 «Литьё и штамповка»: литейный участок и прессы.

Литьё — индукционная тигельная печь (2×2) и литейный участок с ковшом на тельфере и опоками (3×2).
Штамповка — кривошипный пресс (1×1) и листоштамповочный пресс двойного действия (2×1).
Три вида у каждого: спереди, сбоку («_v»), со спины («_b»). Якоря: lamp, glow (зеркало металла),
pour (носик ковша — откуда льётся), ram (ползун пресса: x, y, ширина, ход), in, out, work.

Запуск — из gen_assets.py: gen_v127.run(ga). Плюс значки грузов: шихта, полоса, литые и штампованные детали.
"""
import math

ga = None
OUT = "#23262a"
STEEL, STEEL_D, STEEL_L = "#9aa3a8", "#7b8286", "#cdd3d7"
DARK = "#3a3f43"


def R(*a, **k):
    return ga.rect(*a, **k)


def C(*a, **k):
    return ga.circ(*a, **k)


def L(*a, **k):
    return ga.line(*a, **k)


def P(*a, **k):
    return ga.path(*a, **k)


def B(*a, **k):
    return ga.box(*a, **k)


def E(*a, **k):
    return ga.ell(*a, **k)


def save(key, wt, ht, T0, body, anchors):
    ga.obj(key, wt, ht, T0, body)
    ga.META[key]["anchors"] = anchors


def panel(x, y, w=20, h=34):
    """Пульт: корпус, окошко, три лампы."""
    s = B(x, y, w, 6, h, "#8e9fa8", "#6f8089")
    s += R(x + 3, y + 10, w - 6, 8, "#2a2e31", OUT, 1) + R(x + 5, y + 12, w - 12, 3, "#e8853a", None, 0, 0, 0.8)
    for k in range(3):
        s += C(x + 5 + k * (w - 10) / 2, y + h - 6, 2.0, ["#6fbf86", "#d9b13b", "#c94a3a"][k], OUT, 0.7)
    return s


def mold(x, y, w=22, h=10):
    """Опока: стальная рамка с песком и литником."""
    s = B(x, y, w, 5, h, "#6a6258", "#4f4842")
    s += R(x + 3, y + 1, w - 6, 3, "#b49a72", None, 0)
    s += C(x + w * 0.7, y + 2.5, 1.4, "#2a1d16", None, 0)
    return s


# =============================================================== литьё

def caster(key, wt, ht, kind):
    """ist — индукционная тигельная печь 2×2: тигель на поворотной раме, пульт, опоки на полу.
    line — литейный участок 3×2: печь, ковш на тельфере, рольганг с опоками."""
    W, Hh = wt * 64, ht * 64
    if kind == "ist":
        T0 = 64
        b = ga.shadow(14, T0 - 14, W - 12, Hh + 6)
        b += R(4, T0 + 4, W - 8, Hh - 10, "#8f8b84", OUT, 2, 4)                                    # приямок
        b += R(10, T0 + 30, 8, 40, "#4f5458", OUT, 1.4) + R(W - 60, T0 + 30, 8, 40, "#4f5458", OUT, 1.4)   # стойки поворота
        b += B(16, T0 - 6, W - 84, 10, 52, "#c94a3a", "#a63a2e")                                    # тигель в красном кожухе
        b += E(16 + (W - 84) / 2, T0 - 1, (W - 84) / 2 - 4, 5, "#2a1d16", OUT, 1.4)                 # жерло
        for k in range(3):
            b += L(18, T0 + 14 + k * 12, W - 70, T0 + 14 + k * 12, "#c98d63", 2.2)                     # витки индуктора
        b += P(f"M{W-68} {T0-2}L{W-58} {T0-8}L{W-56} {T0-4}Z", "#a63a2e", OUT, 1.2)                     # носик
        b += panel(W - 40, T0 - 30, 30, 50)
        b += mold(10, T0 + Hh - 26, 24, 10) + mold(38, T0 + Hh - 26, 24, 10)
        cx = 16 + (W - 84) / 2
        an = {"lamp": [W - 33, T0 + 14], "glow": [cx - 16, T0 - 5, 32, 8], "pour": [W - 57, T0 - 6],
              "work": [W * 0.45, T0 + Hh - 12], "in": [14, T0 + Hh - 30], "out": [W - 24, T0 + Hh - 14]}
        save(key, wt, ht, T0, b, an)
        save(key + "_v", ht, wt, T0, b, an)
        bb = ga.shadow(14, T0 - 14, W - 12, Hh + 6) + R(4, T0 + 4, W - 8, Hh - 10, "#8f8b84", OUT, 2, 4)
        bb += B(48, T0 - 6, W - 84, 10, 52, "#c94a3a", "#a63a2e") + E(48 + (W - 84) / 2, T0 - 1, (W - 84) / 2 - 4, 5, "#2a1d16", OUT, 1.4)
        bb += B(10, T0 - 30, 30, 6, 50, "#8e9fa8", "#6f8089") + C(25, T0 + 14, 2.0, "#6fbf86", None, 0)
        bb += mold(W - 34, T0 + Hh - 26, 24, 10)
        save(key + "_b", wt, ht, T0, bb, {"lamp": [25, T0 + 14], "glow": [48 + (W - 84) / 2 - 16, T0 - 5, 32, 8], "pour": [44, T0 - 6],
                                           "work": [W * 0.55, T0 + Hh - 12], "in": [W - 14, T0 + Hh - 30], "out": [24, T0 + Hh - 14]})
        return
    # line 3×2
    T0 = 80
    b = ga.shadow(14, T0 - 30, W - 12, Hh + 22)
    b += R(4, T0 + 8, W - 8, Hh - 12, "#8f8b84", OUT, 2, 4)
    b += B(10, T0 - 10, 54, 10, 58, "#c94a3a", "#a63a2e") + E(37, T0 - 5, 22, 5, "#2a1d16", OUT, 1.4)     # печь
    for k in range(3):
        b += L(12, T0 + 12 + k * 13, 62, T0 + 12 + k * 13, "#c98d63", 2.2)
    b += R(4, T0 - 70, W - 8, 8, "#d9b13b", OUT, 1.6) + L(10, T0 - 62, 10, T0 + 8, "#4f5458", 3) + L(W - 10, T0 - 62, W - 10, T0 + 8, "#4f5458", 3)   # балка тельфера
    b += R(84, T0 - 64, 18, 10, DARK, OUT, 1.2) + L(93, T0 - 54, 93, T0 - 26, "#2a2e31", 1.4)                   # тельфер и трос
    b += P(f"M80 {T0-26}L106 {T0-26}L102 {T0-6}L84 {T0-6}Z", "#6a6258", OUT, 1.6)                           # ковш
    b += E(93, T0 - 25, 12, 3, "#2a1d16", OUT, 1)
    b += R(70, T0 + 36, W - 104, 14, "#5c6267", OUT, 1.4)                                                    # рольганг
    for k in range(int((W - 104) / 10)):
        b += R(72 + k * 10, T0 + 38, 6, 10, STEEL, OUT, 0.8, 3)
    for k in range(3):
        b += mold(74 + k * 30, T0 + 28, 24, 10)
    b += panel(W - 34, T0 - 40, 26, 46)
    an = {"lamp": [W - 27, T0], "glow": [21, T0 - 9, 32, 8], "pour": [104, T0 - 22], "work": [W * 0.4, T0 + Hh - 12],
          "in": [16, T0 + Hh - 14], "out": [W - 22, T0 + Hh - 12]}
    save(key, wt, ht, T0, b, an)
    bv = ga.shadow(14, T0 - 30, Hh - 12, W + 22) + R(4, T0 + 8, Hh - 8, W - 12, "#8f8b84", OUT, 2, 4)
    bv += B(10, T0 - 10, Hh - 30, 10, 54, "#c94a3a", "#a63a2e") + E(10 + (Hh - 30) / 2, T0 - 5, (Hh - 30) / 2 - 4, 5, "#2a1d16", OUT, 1.4)
    bv += R(20, T0 + 80, Hh - 50, 90, "#5c6267", OUT, 1.4) + mold(26, T0 + 100, 30, 10) + mold(26, T0 + 130, 30, 10)
    bv += C(Hh - 14, T0 + 4, 2.0, "#6fbf86", None, 0)
    save(key + "_v", ht, wt, T0, bv, {"lamp": [Hh - 14, T0 + 4], "glow": [Hh * 0.5 - 16, T0 - 9, 32, 8], "pour": [Hh * 0.5 + 18, T0 - 6],
                                       "work": [Hh * 0.45, T0 + W * 0.5], "in": [14, T0 + 70], "out": [Hh - 18, T0 + W - 20]})
    bb = ga.shadow(14, T0 - 30, W - 12, Hh + 22) + R(4, T0 + 8, W - 8, Hh - 12, "#8f8b84", OUT, 2, 4)
    bb += B(W - 64, T0 - 10, 54, 10, 58, "#c94a3a", "#a63a2e") + E(W - 37, T0 - 5, 22, 5, "#2a1d16", OUT, 1.4)
    bb += R(4, T0 - 70, W - 8, 8, "#d9b13b", OUT, 1.6) + R(34, T0 + 36, W - 104, 14, "#5c6267", OUT, 1.4)
    bb += panel(8, T0 - 40, 26, 46)
    save(key + "_b", wt, ht, T0, bb, {"lamp": [15, T0], "glow": [W - 53, T0 - 9, 32, 8], "pour": [W - 104, T0 - 22],
                                       "work": [W * 0.6, T0 + Hh - 12], "in": [W - 16, T0 + Hh - 14], "out": [22, T0 + Hh - 12]})


# =============================================================== штамповка

def press(key, wt, ht, kind):
    """kd — кривошипный пресс 1×1 (станина «С», маховик сбоку).
    kb — листоштамповочный пресс двойного действия 2×1 (две колонны, траверса, рольганг подачи)."""
    W = wt * 64
    if kind == "kd":
        T0 = 70
        b = ga.shadow(12, T0 - 10, 50, 72)
        b += B(14, T0 - 60, 34, 8, 106, "#6d8fae", "#52728f")                              # станина
        b += R(14, T0 - 20, 22, 22, "#2a2e31", OUT, 1.4)                                    # зев
        b += R(16, T0 + 0, 18, 6, STEEL_D, OUT, 1.2)                                        # штамп (нижняя половина)
        b += C(50, T0 - 46, 12, "#4f5458", OUT, 2) + C(50, T0 - 46, 4, STEEL_L, OUT, 1)     # маховик
        b += L(50, T0 - 58, 50, T0 - 34, STEEL_L, 1.2) + L(38, T0 - 46, 62, T0 - 46, STEEL_L, 1.2)
        b += R(4, T0 + 18, 14, 18, "#c9a24a", OUT, 1.2)                                     # педаль/тумба
        b += R(16, T0 - 56, 14, 8, "#2a2e31", OUT, 1) + C(23, T0 - 52, 2.2, "#6fbf86", None, 0)
        an = {"lamp": [23, T0 - 52], "ram": [16, T0 - 20, 18, 12], "work": [25, T0 + 2], "in": [8, T0 + 12], "out": [44, T0 + 20]}
        save(key, 1, 1, T0, b, an)
        save(key + "_v", 1, 1, T0, b, an)
        bb = ga.shadow(12, T0 - 10, 50, 72) + B(16, T0 - 60, 34, 8, 106, "#6d8fae", "#52728f")
        bb += C(14, T0 - 46, 12, "#4f5458", OUT, 2) + C(14, T0 - 46, 4, STEEL_L, OUT, 1)
        for k in range(4):
            bb += L(22, T0 - 30 + k * 10, 44, T0 - 30 + k * 10, "#5e7a96", 1.4)
        save(key + "_b", 1, 1, T0, bb, {"lamp": [40, T0 - 52], "ram": [30, T0 - 20, 18, 12], "work": [39, T0 + 2], "in": [56, T0 + 12], "out": [20, T0 + 20]})
        return
    # kb 2×1
    T0 = 96
    b = ga.shadow(12, T0 - 30, W - 8, 94)
    b += B(14, T0 - 86, W - 28, 14, 30, "#6d8fae", "#52728f")                               # траверса
    b += R(18, T0 - 42, 12, 70, "#52728f", OUT, 1.8) + R(W - 30, T0 - 42, 12, 70, "#52728f", OUT, 1.8)   # колонны
    b += R(30, T0 - 40, W - 60, 40, "#2a2e31", OUT, 1.4)                                       # рабочее пространство
    b += B(26, T0 + 0, W - 52, 6, 16, STEEL, STEEL_D)                                           # стол
    b += R(6, T0 + 4, 20, 10, "#5c6267", OUT, 1.2) + R(W - 26, T0 + 4, 20, 10, "#5c6267", OUT, 1.2)   # подача и съём
    for k in range(3):
        b += C(10 + k * 6, T0 + 9, 2.4, STEEL_L, OUT, 0.8) + C(W - 22 + k * 6, T0 + 9, 2.4, STEEL_L, OUT, 0.8)
    b += R(W * 0.5 - 18, T0 - 82, 36, 10, "#2a2e31", OUT, 1) + R(W * 0.5 - 14, T0 - 80, 20, 5, "#6fd0e0", None, 0, 0, 0.8)
    b += C(W * 0.5 + 12, T0 - 77, 2.2, "#6fbf86", None, 0)
    b += P(f"M{W*0.5-24} {T0-56}L{W*0.5+24} {T0-56}", None, "#d9b13b", 3, dash="6 4")         # жёлто-чёрная полоса
    an = {"lamp": [W * 0.5 + 12, T0 - 77], "ram": [34, T0 - 40, W - 68, 14], "work": [W * 0.5, T0 + 4], "in": [14, T0 + 2], "out": [W - 16, T0 + 2]}
    save(key, 2, 1, T0, b, an)
    bv = ga.shadow(12, T0 - 30, 52, 128 + 30) + B(8, T0 - 86, 48, 14, 30, "#6d8fae", "#52728f")
    bv += R(12, T0 - 42, 10, 100, "#52728f", OUT, 1.8) + R(42, T0 - 42, 10, 100, "#52728f", OUT, 1.8)
    bv += R(22, T0 - 40, 20, 80, "#2a2e31", OUT, 1.4) + B(14, T0 + 30, 36, 6, 16, STEEL, STEEL_D) + C(32, T0 - 77, 2.2, "#6fbf86", None, 0)
    save(key + "_v", 1, 2, T0, bv, {"lamp": [32, T0 - 77], "ram": [22, T0 - 40, 20, 14], "work": [32, T0 + 40], "in": [32, T0 + 2], "out": [32, T0 + 90]})
    bb = ga.shadow(12, T0 - 30, W - 8, 94) + B(14, T0 - 86, W - 28, 14, 30, "#6d8fae", "#52728f")
    bb += R(18, T0 - 42, 12, 70, "#52728f", OUT, 1.8) + R(W - 30, T0 - 42, 12, 70, "#52728f", OUT, 1.8)
    for k in range(4):
        bb += L(34, T0 - 34 + k * 10, W - 34, T0 - 34 + k * 10, "#5e7a96", 1.4)
    bb += C(W * 0.5 - 12, T0 - 77, 2.2, "#6fbf86", None, 0)
    save(key + "_b", 2, 1, T0, bb, {"lamp": [W * 0.5 - 12, T0 - 77], "ram": [34, T0 - 40, W - 68, 14], "work": [W * 0.5, T0 + 4], "in": [W - 14, T0 + 2], "out": [16, T0 + 2]})


# =============================================================== значки грузов 32×32

def items():
    def it(key, body):
        ga.save(f"assets/items/{key}.svg", 32, 32, body)
    sh = E(16, 27, 13, 3, "#000", None, 0, 0.25)
    # шихта: чушки и обрезки
    s = sh + P("M4 22L12 14L20 14L14 22Z", "#8c8f94", OUT, 1.3) + P("M12 24L20 16L28 16L22 24Z", "#7a7d82", OUT, 1.3)
    s += P("M6 12L10 6L14 9L11 13Z", "#9a6a4a", OUT, 1.1) + P("M18 10L24 6L26 11L20 12Z", "#a07a5a", OUT, 1.1)
    it("charge", s)
    # полоса 2 мм: стопка узких листов
    s = sh
    for k in range(3):
        s += P(f"M3 {20-k*3}L23 {12-k*3}L29 {14-k*3}L9 {22-k*3}Z", ["#b9c2c8", "#a9b3ba", "#c7cfd4"][k], OUT, 1.1)
    it("strip2", s)
    # крышка литая: серый чугунный диск с рёбрами
    s = sh + E(16, 17, 13, 9, "#6e7377", OUT, 1.5) + E(16, 15, 10, 6.5, "#80868a", OUT, 1.1) + E(16, 14, 3.5, 2.4, "#4a4e52", OUT, 1)
    for k in range(4):
        a = k * math.pi / 2 + 0.4
        s += L(16 + math.cos(a) * 4, 14 + math.sin(a) * 2.8, 16 + math.cos(a) * 9, 15 + math.sin(a) * 6, "#5a5f63", 1.4)
    it("cast_cover", s)
    # корпус редуктора литой
    s = sh + B(5, 9, 22, 6, 12, "#7a8086", "#61676c") + C(11, 17, 3.2, "#3a3f43", OUT, 1) + C(21, 17, 3.2, "#3a3f43", OUT, 1)
    s += R(3, 21, 26, 3, "#61676c", OUT, 1)
    it("cast_body", s)
    # шайба: стопка колец
    s = sh
    for k in range(3):
        s += E(16, 21 - k * 4, 10, 4, ["#b4bcc0", "#c4cbcf", "#d2d8db"][k], OUT, 1.2) + E(16, 21 - k * 4, 3.6, 1.4, "#3a3f43", None, 0)
    it("washer", s)
    # хомут: согнутая полоса с ушками
    s = sh + P("M6 20Q6 6 16 6Q26 6 26 20", None, OUT, 5.4) + P("M6 20Q6 6 16 6Q26 6 26 20", None, "#b9c2c8", 3.4)
    s += R(2, 19, 8, 4, "#a9b3ba", OUT, 1) + R(22, 19, 8, 4, "#a9b3ba", OUT, 1)
    it("clamp", s)
    # кронштейн гнутый: уголок с отверстиями
    s = sh + P("M6 24L6 8L12 8L12 18L26 18L26 24Z", "#b0b8bd", OUT, 1.4) + C(9, 12, 1.4, "#3a3f43", None, 0) + C(20, 21, 1.4, "#3a3f43", None, 0)
    it("bracket_st", s)
    # формовочная смесь (расходник)
    s = sh + P("M7 25L9 10L23 10L25 25Z", "#c9b48a", OUT, 1.4) + P("M9 10Q16 5 23 10", None, OUT, 1.2) + R(11, 15, 10, 5, "#8a7450", None, 0, 0, 0.6)
    it("sand", s)


def run(module):
    global ga
    ga = module
    caster("cast_ist", 2, 2, "ist")
    caster("cast_line", 3, 2, "line")
    press("press_kd", 1, 1, "kd")
    press("press_kb", 2, 1, "kb")
    items()
